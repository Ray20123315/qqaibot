function normalizePortalLocale(value) {
  const raw = String(value || "").trim();
  if (!raw) return "zh-TW";
  const lower = raw.toLowerCase();
  if (lower === "zh" || lower.startsWith("zh-tw") || lower.startsWith("zh-hk") || lower.startsWith("zh-hant")) return "zh-TW";
  if (lower.startsWith("zh-cn") || lower.startsWith("zh-sg") || lower.startsWith("zh-hans")) return "zh-CN";
  if (lower.startsWith("pt")) return "pt-BR";
  const exact = PORTAL_LOCALES.find(item => item.id.toLowerCase() === lower);
  if (exact) return exact.id;
  const base = lower.split("-")[0];
  return PORTAL_LOCALES.find(item => item.id.toLowerCase().split("-")[0] === base)?.id || "en";
}

function portalMessage(locale, key) {
  const normalized = normalizePortalLocale(locale);
  const selected = PORTAL_MESSAGES[normalized] || {};
  const fallback = PORTAL_MESSAGES.en || {};
  return selected[key] ?? fallback[key] ?? key;
}

function portalI18nPayload() {
  return Object.freeze({ locales: PORTAL_LOCALES, messages: PORTAL_MESSAGES, defaultLocale: "zh-TW", fallbackLocale: "en" });
}

export { PORTAL_LOCALES, PORTAL_MESSAGES, normalizePortalLocale, portalI18nPayload, portalMessage };
