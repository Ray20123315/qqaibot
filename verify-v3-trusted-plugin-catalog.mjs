import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import { createBilibiliLivePlugin } from "./src/plugins/official/bilibili-live.js";
import { BILIBILI_LIVE_SOURCE_SHA256, trustedBundledPluginById, trustedBundledPluginCatalog, trustedBundledPluginIds } from "./src/plugins/catalog.js";

const catalog = trustedBundledPluginCatalog();
assert.equal(catalog.length, 1);
assert.deepEqual(trustedBundledPluginIds(), ["official.bilibili-live"]);
const entry = trustedBundledPluginById("official.bilibili-live");
assert(entry);
assert.equal(entry.trustedBundled, true);
assert.equal(entry.integrityScope, "bundled-source-build-verified");
assert.equal(entry.descriptor.integrity, "sha256:" + BILIBILI_LIVE_SOURCE_SHA256);
assert.equal(entry.descriptor.id, createBilibiliLivePlugin({}).manifest.id);
assert.equal(entry.descriptor.version, createBilibiliLivePlugin({}).manifest.version);
const source = fs.readFileSync(entry.sourcePath);
const sourceHash = crypto.createHash("sha256").update(source).digest("hex");
assert.equal(sourceHash, BILIBILI_LIVE_SOURCE_SHA256, "catalog source SHA-256 must match the bundled source file");
console.log("verify-v3-trusted-plugin-catalog: ok");
